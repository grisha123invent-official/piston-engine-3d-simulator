/**
 * Общие размеры 3D-сцены. Единица сцены = 10 мм реального двигателя.
 * Все модули (механизм, жидкости, интегратор) строятся по этим числам,
 * чтобы детали совпадали между собой.
 */

const BORE_MM = 86, STROKE_MM = 86, ROD_MM = 143;

export const L = {
  // ── масштаб ──
  MM: 0.1,                       // мм → юниты сцены

  // ── кривошипно-шатунный механизм ──
  BORE_R: BORE_MM * 0.1 / 2,     // 4.3 — радиус цилиндра
  CRANK_R: STROKE_MM * 0.1 / 2,  // 4.3 — радиус кривошипа
  ROD_L: ROD_MM * 0.1,           // 14.3 — длина шатуна
  STROKE_U: STROKE_MM * 0.1,     // 8.6 — полный ход поршня
  PISTON_H: 5.4,                 // высота юбки поршня
  PISTON_TOP_OFF: 3.2,           // от оси пальца до днища поршня

  // ── головка ──
  /** Высота камеры сгорания (юниты) при данной степени сжатия. */
  clearance(eps) { return (STROKE_MM * 0.1) / (eps - 1); },
  /** Плоскость головки блока: зависит от ε, поршень в ВМТ стоит на clearance ниже неё. */
  deckY(eps) {
    return STROKE_MM * 0.05 + ROD_MM * 0.1 + 3.2 + (STROKE_MM * 0.1) / (eps - 1);
  },
  HEAD_H: 3.4,                   // толщина головки

  // ── цилиндры (ось коленвала — Z) ──
  CYL_Z: [-16.5, -5.5, 5.5, 16.5],   // позиции цилиндров 1..4 вдоль вала
  CYL_Z_SINGLE: [0],
  /** Смещение цикла для цилиндров 1..4 при порядке работы 1–3–4–2. */
  CYL_PHASE: [0, 540, 180, 360],
  /** Смещение кривошипа: цил. 1 и 4 — вверх, 2 и 3 — вниз. */
  CRANK_PHASE: [0, 180, 180, 0],

  // ── клапаны и распредвалы ──
  VALVE_X_IN: -2.05,
  VALVE_X_EX: 2.05,
  VALVE_HEAD_R: 1.3,
  VALVE_LIFT_MAX: 1.05,          // максимальный подъём (≈10.5 мм)
  CAM_DY: 5.4,                   // высота осей распредвалов над плоскостью головки
  CAM_R: 1.15,                   // базовый радиус кулачка
  CAM_LOBE: 1.05,                // высота профиля кулачка

  // ── коленвал, маховик, привод ГРМ ──
  MAIN_R: 1.15,                  // радиус коренной шейки
  PIN_R: 0.95,                   // радиус шатунной шейки
  FLYWHEEL_R: 6.4,
  FLYWHEEL_Z_SINGLE: 5.6,
  FLYWHEEL_Z_I4: 22.5,
  SPROCKET_CRANK_R: 1.5,         // звёздочка коленвала (вдвое меньше кулачковой)
  SPROCKET_CAM_R: 3.0,
  CHAIN_Z: -22.0,                // плоскость цепи ГРМ (перед первым цилиндром)

  // ── рубашка охлаждения ──
  JACKET_GAP: 1.15,              // зазор между стенкой цилиндра и рубашкой
  SUMP_Y: -9.5,                  // уровень масла в поддоне

  // ── V-образная компоновка ──
  BANK_TILT: Math.PI / 4,        // ±45° от вертикали, развал 90°
  V8_Z: [-18, -6, 6, 18],        // позиции пар цилиндров вдоль вала

  // ── двухтактный вариант: окна в стенке цилиндра (доля хода от ВМТ) ──
  PORT_EXH_TOP: 0.62, PORT_EXH_BOT: 0.86,      // выпускное окно
  PORT_TR_TOP: 0.74,  PORT_TR_BOT: 0.94,       // продувочные окна
  CRANKCASE_H: 7.5,                            // высота кривошипной камеры

  // ── турбокомпрессор и интеркулер ──
  TURBO_POS: [11.5, 6.5, -13],
  INTERCOOLER_POS: [-12.5, 9.5, -13],
  INTAKE_LEN_REF: 350,           // мм, которым соответствует базовая длина патрубка

  // ── общее ──
  GRID_Y: -11,
};

/**
 * Описание компоновки: наклон ряда, положение вдоль вала, смещение цикла.
 * V8 — развал 90°, крестообразный вал, порядок работы 1–8–4–3–6–5–7–2.
 */
export const LAYOUTS = {
  single: { cylinders: 1, name: 'Одноцилиндровый',
    cyl: [{ z: 0, tilt: 0, phase: 0, pin: 0 }] },

  /* Порядок работы 1–3–4–2: цилиндр вспыхивает при (угол цикла + phase) = 360°,
     поэтому раньше загорается тот, у кого phase больше. */
  i4: { cylinders: 4, name: 'Рядная 4',
    cyl: [
      { z: -16.5, tilt: 0, phase: 0,   pin: 0 },
      { z: -5.5,  tilt: 0, phase: 180, pin: 180 },
      { z: 5.5,   tilt: 0, phase: 540, pin: 180 },
      { z: 16.5,  tilt: 0, phase: 360, pin: 0 },
    ] },

  /* Оппозитная четвёрка: ряды горизонтальные (±90°), у противолежащих цилиндров
     свои шатунные шейки со сдвигом 180° — это и отличает боксёр от V-образника
     с развалом 180°. Порядок работы 1–3–2–4. */
  boxer4: { cylinders: 4, name: 'Оппозитная 4',
    cyl: [
      { z: -8, tilt: -Math.PI / 2, phase: 0,   pin: 0 },    // цил. 1, левый ряд
      { z: -8, tilt:  Math.PI / 2, phase: 360, pin: 180 },  // цил. 2, правый
      { z:  8, tilt: -Math.PI / 2, phase: 540, pin: 180 },  // цил. 3, левый
      { z:  8, tilt:  Math.PI / 2, phase: 180, pin: 0 },    // цил. 4, правый
    ] },

  v8: { cylinders: 8, name: 'V8, развал 90°',
    cyl: [
      { z: -18, tilt: -Math.PI / 4, phase: 0,   pin: 0 },    // цил. 1, левый ряд
      { z: -18, tilt:  Math.PI / 4, phase: 630, pin: 0 },    // цил. 2, правый
      { z: -6,  tilt: -Math.PI / 4, phase: 270, pin: 90 },   // цил. 3
      { z: -6,  tilt:  Math.PI / 4, phase: 180, pin: 90 },   // цил. 4
      { z: 6,   tilt: -Math.PI / 4, phase: 450, pin: 270 },  // цил. 5
      { z: 6,   tilt:  Math.PI / 4, phase: 360, pin: 270 },  // цил. 6
      { z: 18,  tilt: -Math.PI / 4, phase: 540, pin: 180 },  // цил. 7
      { z: 18,  tilt:  Math.PI / 4, phase: 90,  pin: 180 },  // цил. 8
    ] },
};

/** Компоновка по имени с безопасным запасным вариантом. */
export function layoutSpec(name){
  return LAYOUTS[name] || LAYOUTS.single;
}

/** Позиции цилиндров вдоль оси Z для заданного их числа. */
export function cylinderZ(n) {
  return n === 1 ? L.CYL_Z_SINGLE : L.CYL_Z;
}

/** Смещение цикла (град.) для цилиндра с индексом i при заданном их числе. */
export function cylinderPhase(i, n) {
  return n === 1 ? 0 : L.CYL_PHASE[i];
}

/** Положение оси поршневого пальца по углу коленвала (юниты, от оси вала). */
export function pinY(crankRad) {
  return L.CRANK_R * Math.cos(crankRad)
       + Math.sqrt(L.ROD_L * L.ROD_L - (L.CRANK_R * Math.sin(crankRad)) ** 2);
}

/** Ось пальца в ВМТ и НМТ. */
export const PIN_Y_TDC = L.CRANK_R + L.ROD_L;
export const PIN_Y_BDC = L.ROD_L - L.CRANK_R;
